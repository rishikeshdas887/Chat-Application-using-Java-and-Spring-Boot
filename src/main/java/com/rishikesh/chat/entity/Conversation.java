package com.rishikesh.chat.entity;

import java.time.LocalDateTime;

import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated; //every conversation corresponds to table in Db named conversations
import jakarta.persistence.GeneratedValue; //every conversation unique identificaton
import jakarta.persistence.GenerationType;//user qill not get random id it should be generated by database
import jakarta.persistence.Id; //user qill not get random id it should be generated by database
import jakarta.persistence.Table; //enum is used for fixed options

@Entity
@Table(name = "conversations")

public class Conversation {
  @Id // says database that this is primary key
  @GeneratedValue(strategy = GenerationType.IDENTITY) // THIS TELLS THE SYSTEM HOW TO CREATE IDs
  private Long id;

  @Enumerated(EnumType.STRING) // enum is used for fixed options
  private ConversationType type; // to check the conversation Id is group or private chat

  public enum ConversationType {
    PRIVATE,
    GROUP
  } // so now database mein tye field mein se ek value hogi

  private String name;
  private LocalDateTime createdAt; // kab create hua wo chat (private / public kuch bhi ho )
}
