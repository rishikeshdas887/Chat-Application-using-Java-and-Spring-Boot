package com.rishikesh.chat.entity;

import java.time.LocalDateTime;

import com.rishikesh.chat.enums.ConversationType;

import jakarta.persistence.Entity;
import jakarta.persistence.EnumType; //every conversation corresponds to table in Db named conversations
import jakarta.persistence.Enumerated; //every conversation unique identificaton
import jakarta.persistence.GeneratedValue;//user qill not get random id it should be generated by database
import jakarta.persistence.GenerationType; //user qill not get random id it should be generated by database
import jakarta.persistence.Id; //enum is used for fixed options
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;

@Entity
@Table(name = "conversations")

public class Conversation {
  @Id // says database that this is primary key
  @GeneratedValue(strategy = GenerationType.IDENTITY) // THIS TELLS THE SYSTEM HOW TO CREATE IDs
  private Long id;

  @Enumerated(EnumType.STRING) // enum is used for fixed options
  private ConversationType type; // to check the conversation Id is group or private chat

  private String name;
  private LocalDateTime createdAt; // kab create hua wo chat (private / public kuch bhi ho )

  // <---------------Getters-------------->

  public Long getId() {
    return id;
  }

  public ConversationType getType() {
    return type;
  }

  public LocalDateTime getCreatedAt() {
    return createdAt; // conversation created time
  }

  public String getName() {
    return name;
  }

  // <-------------------------Setters----------------------->
  public void setType(ConversationType type) {
    this.type = type;
  }

  public void setCreatedAt(LocalDateTime createdAt) {
    this.createdAt = createdAt;
  }

  public void setName(String name) {
    this.name = name;
  }

  @PrePersist
  protected void onCreate() {
    if (createdAt == null) {
      createdAt = LocalDateTime.now();
    }
  }

}
