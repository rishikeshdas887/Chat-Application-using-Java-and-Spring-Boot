package com.rishikesh.chat.entity;

import java.time.LocalDateTime;

import com.rishikesh.chat.enums.UserStatus;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

@Entity
@Table(name = "users") // java class corresponds to table in Db named users

public class User {

    // <--------------------Annotations are additiona information to code , method ,
    // class , etc------------->
    @Id // variable unique id specfied for a user
    @GeneratedValue(strategy = GenerationType.IDENTITY) // THIS TELLS THE SYSTEM HOW TO CREATE IDs

    private Long id;
    private String username;
    private String email;
    private String hashedPassword;
    private LocalDateTime createdAt;

    private UserStatus status;

    public Long getId() {
        return id; // every class needs id generated by the database and this method returns the Id
    }

    public String getUsername() {
        return username; // any class requires username and this method returns the username
    }

    public String getEmail() {
        return email;
    }

    public String getHashedPassword() {
        return hashedPassword;
    }

    public LocalDateTime getCreatedAt() {

        return createdAt;
    }

    public UserStatus getStatus() {
        return status;
    }

    // setters -------------------->

    public void setUsername(String username) {
        this.username = username;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public void setHashedPassword(String hashedPassword) {
        this.hashedPassword = hashedPassword;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }

    public void setStatus(UserStatus status) {
        this.status = status;
    }

}
